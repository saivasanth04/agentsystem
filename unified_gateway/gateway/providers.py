def find_provider_metadata(name_or_id: str) -> Optional[ProviderMetadata]:
    """Finds provider metadata by ID or alias (case-insensitive)."""
    norm = name_or_id.lower().strip()
    if norm in PROVIDER_METADATA_REGISTRY:
        return PROVIDER_METADATA_REGISTRY[norm]

    for spec in PROVIDER_METADATA_REGISTRY.values():
        if norm == spec.id.lower() or norm == spec.name.lower():
            return spec
        if any(norm == a.lower() for a in spec.aliases):
            return spec

    # Partial match
    for spec in PROVIDER_METADATA_REGISTRY.values():
        if norm in spec.id.lower() or norm in spec.name.lower():
            return spec
    return None
