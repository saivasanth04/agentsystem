"""
Provider Metadata Registry for Unified LLM Gateway.
Contains ONLY immutable provider definitions:
- Provider ID
- Base URL
- Authentication strategy (header name, prefix, auth type)
- Discovery endpoint (/models or provider-specific)
- Capability flags
- API format & LiteLLM provider prefix

NEVER store model names in this file. Model discovery is 100% dynamic.
"""
from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class ProviderMetadata(BaseModel):
    id: str
    name: str
    aliases: List[str] = Field(default_factory=list)
    base_url: str
    chat_endpoint: str = "/chat/completions"
    models_endpoint: Optional[str] = "/models"
    auth_type: str = "bearer"  # "bearer", "header", "none", "query"
    auth_header_name: str = "Authorization"
    auth_header_prefix: str = "Bearer "
    litellm_prefix: str = "openai/"
    api_format: str = "openai"  # "openai", "gemini", "anthropic", "mistral"
    default_rpm_limit: int = 60
    default_tpm_limit: int = 100_000
    supports_streaming: bool = True
    supports_tools: bool = True
    supports_vision: bool = True
    supports_embeddings: bool = False
    base_priority: int = 50
    extra_headers: Dict[str, str] = Field(default_factory=dict)


